def main():
    parser = argparse.ArgumentParser(
        description="Generate FastAPI CRUD router from SQLModel/Pydantic model"
    )
    parser.add_argument(
        "model",
        help="Model definition as string or path to file containing model"
    )
    parser.add_argument(
        "--pattern",
        choices=["direct", "repository"],
        default="direct",
        help="Architecture pattern (direct DB operations or repository pattern)"
    )
    parser.add_argument(
        "--session",
        choices=["generate", "assume"],
        default="generate",
        help="Session management: generate get_session() or assume get_db() exists"
    )
    parser.add_argument(
        "-o", "--output",
        help="Output file path (default: stdout)"
    )

    args = parser.parse_args()

    # Read model definition
    model_code = args.model
    try:
        with open(model_code, 'r') as f:
            model_code = f.read()
    except FileNotFoundError:
        # Assume it's the model code itself
        pass
    except Exception as e:
        print(f"Error reading file: {e}", file=sys.stderr)
        sys.exit(1)

    # Parse model
    try:
        model_info = parse_model_definition(model_code)
    except ValueError as e:
        print(f"Error parsing model: {e}", file=sys.stderr)
        sys.exit(1)

    # Generate code
    if args.pattern == "direct":
        code = generate_direct_pattern(model_info, args.session)
    else:
        code = generate_repository_pattern(model_info, args.session)

    # Output
    if args.output:
        try:
            with open(args.output, 'w') as f:
                f.write(code)
            print(f"Generated CRUD router written to {args.output}", file=sys.stderr)
        except Exception as e:
            print(f"Error writing output: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        print(code)


if __name__ == "__main__":
    main()
