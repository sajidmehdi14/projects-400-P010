def parse_model_definition(model_code: str) -> Dict[str, Any]:
    """Parse SQLModel/Pydantic model definition to extract metadata."""
    try:
        tree = ast.parse(model_code)
    except SyntaxError as e:
        raise ValueError(f"Invalid Python code: {e}")

    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef):
            model_name = node.name
            fields = []
            bases = [base.id if isinstance(base, ast.Name) else str(base) for base in node.bases]

            # Extract fields from class body
            for item in node.body:
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    field_name = item.target.id
                    field_type = ast.unparse(item.annotation)

                    # Check if field is optional
                    is_optional = 'Optional' in field_type or '| None' in field_type or 'None |' in field_type
                    has_default = item.value is not None

                    fields.append({
                        'name': field_name,
                        'type': field_type,
                        'optional': is_optional or has_default
                    })

            return {
                'name': model_name,
                'fields': fields,
                'bases': bases,
                'table_name': model_name.lower() + 's'
            }

    raise ValueError("No class definition found in model code")


